module projection_tb;

    // -----------------------------------------------------------------
    // Parameters & Signals
    // -----------------------------------------------------------------
    localparam DATA_W = 16;
    localparam Q_FRAC = 12;

    reg                 clk;
    reg                 rst;
    
    // Inputs to Top Module
    reg                 valid_in;
    reg  [DATA_W-1:0]   radar_input;
    reg                 start_layer;
    reg  [8:0]          next_layer_raddr;

    // Outputs from Top Module
    wire                layer_done;
    wire [DATA_W-1:0]   next_layer_rdata;

    // -----------------------------------------------------------------
    // Instantiate the Top Module (Device Under Test)
    // -----------------------------------------------------------------
    top_projection #(
        .DATA_W(DATA_W),
        .Q_FRAC(Q_FRAC)
    ) dut (
        .clk(clk),
        .rst(rst),
        .valid_in(valid_in),
        .radar_input(radar_input),
        .start_layer(start_layer),
        .layer_done(layer_done),
        .next_layer_raddr(next_layer_raddr),
        .next_layer_rdata(next_layer_rdata)
    );

    // -----------------------------------------------------------------
    // Clock Generation (100 MHz)
    // -----------------------------------------------------------------
    initial clk = 0;
    always #5 clk = ~clk;

    // -----------------------------------------------------------------
    // Test Memories & Variables
    // -----------------------------------------------------------------
    reg [15:0] test_input_mem   [0:879]; // 10 rows x 88 features
    reg [15:0] expected_out_mem [0:319]; // 10 rows x 32 features

    integer i;
    integer errors = 0;
    reg signed [15:0] exp_val;
    reg signed [15:0] act_val;

    // -----------------------------------------------------------------
    // Main Simulation Sequence
    // -----------------------------------------------------------------
    initial begin
        $display("================================================================");
        $display(" Starting Simulation: Projection_Top (Master/Slave Architecture)");
        $display("================================================================");

        // 1. Load the exact bit-accurate files generated by Python
        $readmemh("test_input.mem", test_input_mem);
        $readmemh("expected_out.mem", expected_out_mem);

        // 2. Initialize Signals & Reset
        valid_in         = 1'b0;
        radar_input      = 16'd0;
        start_layer      = 1'b0;
        next_layer_raddr = 9'd0;
        rst              = 1'b1;

        #25;
        @(posedge clk);
        rst = 1'b0;
        @(posedge clk);

        // -------------------------------------------------------------
        // PHASE 1: Stream 880 serial radar samples into the module
        // -------------------------------------------------------------
        $display("--> Phase 1: Streaming 880 values into Projection_Top...");
        for (i = 0; i < 880; i = i + 1) begin
            @(posedge clk);
            valid_in    <= 1'b1;
            radar_input <= test_input_mem[i];
        end

        // De-assert streaming signals
        @(posedge clk);
        valid_in    <= 1'b0;
        radar_input <= 16'd0;
        $display("--> Phase 1 Complete. Buffer full.");

        // -------------------------------------------------------------
        // PHASE 2: Trigger MAC computation
        // -------------------------------------------------------------
        @(posedge clk);
        start_layer <= 1'b1;
        $display("--> Phase 2: Triggering start_layer...");
        
        @(posedge clk);
        start_layer <= 1'b0; // Pulse for just 1 cycle

        // -------------------------------------------------------------
        // PHASE 3: Wait for hardware to process 10 rows
        // -------------------------------------------------------------
        $display("--> Phase 3: Hardware computing (Waiting for layer_done)...");
        wait (layer_done == 1'b1);
        @(posedge clk);
        $display("--> Phase 3 Complete. layer_done asserted.");

        // -------------------------------------------------------------
        // PHASE 4: Verify downstream BRAM contents
        // -------------------------------------------------------------
        $display("--> Phase 4: Reading Tensor_BRAM via downstream port...");
        for (i = 0; i < 320; i = i + 1) begin
            @(posedge clk);
            next_layer_raddr <= i[8:0]; // Request address
            
            @(posedge clk);             // Wait 1 cycle for BRAM read latency
            #1;                         // Small delay to read stable signal

            exp_val = expected_out_mem[i];
            act_val = next_layer_rdata;

            if (act_val !== exp_val) begin
                $display("[FAIL] Addr %0d (Row %0d, Feat %0d): Expected %04x, Got %04x",
                         i, i / 32, i % 32, exp_val, act_val);
                errors = errors + 1;
            end else if (i % 32 == 0) begin
                // Print a heartbeat message at the start of every new row
                $display("[PASS] Row %0d Feature 0 verified: %04x", i / 32, act_val);
            end
        end

        // -------------------------------------------------------------
        // Final Report
        // -------------------------------------------------------------
        $display("================================================================");
        if (errors == 0) begin
            $display(" [SUCCESS] All 320 outputs matched the Python golden model!");
        end else begin
            $display(" [FAILURE] Encountered %0d mismatches.", errors);
        end
        $display("================================================================");
        $finish;
    end

endmodule
